package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"

	"golang.org/x/tools/go/ast/astutil"
)

func main() {
	source := flag.String("source", "", "CAPO module source directory")
	output := flag.String("output", ".", "output directory")
	flag.Parse()
	if err := generate(*source, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(source, output string) error {
	if source == "" {
		_, filename, _, _ := runtime.Caller(0)
		command := exec.CommandContext(context.Background(), "go", "mod", "download", "-json", "sigs.k8s.io/cluster-api-provider-openstack")
		command.Dir = filepath.Join(filepath.Dir(filename), "..", "capi-vendor", "openstack")
		command.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=", "GO111MODULE=on")
		data, err := command.Output()
		if err != nil {
			return fmt.Errorf("resolve CAPO source: %w", err)
		}
		var module struct{ Dir string }
		if err := json.Unmarshal(data, &module); err != nil {
			return err
		}
		source = module.Dir
	}
	files, err := filepath.Glob(filepath.Join(source, "api", "v1beta1", "*.go"))
	if err != nil {
		return err
	}
	types := map[string]bool{}
	for _, filename := range files {
		file, err := parser.ParseFile(token.NewFileSet(), filename, nil, 0)
		if err != nil {
			return err
		}
		ast.Inspect(file, func(node ast.Node) bool {
			if declaration, ok := node.(*ast.TypeSpec); ok {
				types[declaration.Name.Name] = true
			}
			return true
		})
	}
	for _, relative := range []string{"api/v1beta1/conversion.go", "api/v1beta1/zz_generated.conversion.go", "api/v1beta2/conversion_helpers.go"} {
		data, err := os.ReadFile(filepath.Join(source, relative))
		if err != nil {
			return err
		}
		converted, err := localize(data, types, strings.Contains(relative, "v1beta2/"))
		if err != nil {
			return fmt.Errorf("localize %s: %w", relative, err)
		}
		name := "zz_generated.manual.go"
		if strings.Contains(relative, "zz_generated.") {
			name = "zz_generated.mapping.go"
		} else if beta2 := strings.Contains(relative, "v1beta2/"); beta2 {
			name = "zz_generated.conditions.go"
		}
		if err := os.WriteFile(filepath.Join(output, name), converted, 0644); err != nil {
			return err
		}
	}
	return nil
}

func localize(data []byte, types map[string]bool, beta2 bool) ([]byte, error) {
	fileSet := token.NewFileSet()
	file, err := parser.ParseFile(fileSet, "conversion.go", data, 0)
	if err != nil {
		return nil, err
	}
	file.Name.Name = "openstackconversion"
	declarations := file.Decls[:0]
	for _, declaration := range file.Decls {
		if function, ok := declaration.(*ast.FuncDecl); ok && (function.Recv != nil || function.Name.Name == "init" || function.Name.Name == "RegisterConversions") {
			continue
		}
		declarations = append(declarations, declaration)
	}
	file.Decls = declarations
	for _, imported := range file.Imports {
		path, err := strconv.Unquote(imported.Path.Value)
		if err != nil {
			return nil, err
		}
		if strings.HasPrefix(path, "sigs.k8s.io/cluster-api/api/") {
			imported.Path.Value = strconv.Quote(strings.Replace(path, "sigs.k8s.io/cluster-api/api/", "sigs.k8s.io/cluster-api-provider-openstack/capicore/api/", 1))
		}
	}
	astutil.Apply(file, func(cursor *astutil.Cursor) bool {
		switch node := cursor.Node().(type) {
		case *ast.SelectorExpr:
			if node.Sel.Name == "ConditionSeverityNone" {
				cursor.Replace(&ast.BasicLit{Kind: token.STRING, Value: `""`})
				return false
			}
			if identifier, ok := node.X.(*ast.Ident); ok && identifier.Name == "infrav1" && (strings.HasPrefix(node.Sel.Name, "ConvertConditions") || node.Sel.Name == "IsReady") {
				cursor.Replace(ast.NewIdent(node.Sel.Name))
			}
		case *ast.Ident:
			if beta2 {
				if node.Name == "ReadyConditionReason" {
					cursor.Replace(&ast.SelectorExpr{X: ast.NewIdent("infrav1"), Sel: ast.NewIdent(node.Name)})
				}
				return true
			}
			if !types[node.Name] {
				return true
			}
			if selector, ok := cursor.Parent().(*ast.SelectorExpr); ok && selector.Sel == node {
				return true
			}
			if field, ok := cursor.Parent().(*ast.KeyValueExpr); ok && field.Key == node {
				return true
			}
			cursor.Replace(&ast.SelectorExpr{X: ast.NewIdent("capov1beta1"), Sel: ast.NewIdent(node.Name)})
		}
		return true
	}, nil)
	astutil.AddNamedImport(fileSet, file, "capov1beta1", "sigs.k8s.io/cluster-api-provider-openstack/api/v1beta1")
	if beta2 {
		astutil.AddNamedImport(fileSet, file, "infrav1", "sigs.k8s.io/cluster-api-provider-openstack/api/v1beta2")
	}
	removeUnusedImports(fileSet, file)
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by hack/copy-capo-conversions from CAPO v0.15.0. DO NOT EDIT.\n\n")
	if err := format.Node(&buffer, fileSet, file); err != nil {
		return nil, err
	}
	return format.Source(buffer.Bytes())
}

func removeUnusedImports(fileSet *token.FileSet, file *ast.File) {
	used := map[string]bool{}
	ast.Inspect(file, func(node ast.Node) bool {
		if selector, ok := node.(*ast.SelectorExpr); ok {
			if identifier, ok := selector.X.(*ast.Ident); ok {
				used[identifier.Name] = true
			}
		}
		return true
	})
	for _, imported := range append([]*ast.ImportSpec(nil), file.Imports...) {
		path, _ := strconv.Unquote(imported.Path.Value)
		name := filepath.Base(path)
		if imported.Name != nil {
			name = imported.Name.Name
		}
		if !used[name] {
			astutil.DeleteNamedImport(fileSet, file, "", path)
			if imported.Name != nil {
				astutil.DeleteNamedImport(fileSet, file, imported.Name.Name, path)
			}
		}
	}
}
