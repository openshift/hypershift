type ownershipGroup struct {
	Name   string   `json:"name"`
	Prefix string   `json:"prefix"`
	Types  []string `json:"types"`
	Owns   string   `json:"owns"`
}
type ownershipRule struct {
	Pattern string `json:"pattern"`
	Group   string `json:"group"`
	Why     string `json:"why"`
}
type ownershipPolicy struct {
	Groups            []ownershipGroup
	BinaryGroups      map[string]string
	Conventions       [][3]string
	ModuleGroups      map[string]string
	RootSources       []string
	DocDirs           []string
	GeneratedPatterns []string
}
type ownershipBinary struct{ name, group, dir string }
type ownershipFacts struct {
	paths      []string
	binaries   []ownershipBinary
	importers  map[string][]string
	generated  map[string]bool
	outputDirs []string
}

