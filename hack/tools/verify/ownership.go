func (r *runner) ownership() error {
	dir := filepath.Join(r.root, "skills/restructure-commits")
	policy := repositoryOwnership
	facts, err := r.ownershipFacts(policy)
	if err != nil {
		return err
	}
	rules := ownershipRules(policy, facts)
	description := "GENERATED by make ownership-rules (make update); do not edit. Groups are listed in commit order. Rules are evaluated top to bottom and the first matching pattern wins. Patterns are anchored at the repository root; '**' matches zero or more path segments and other wildcards never cross '/'."
	var out strings.Builder
	descriptionJSON, err := json.Marshal(description)
	if err != nil {
		return err
	}
	fmt.Fprintf(&out, "{\n  \"description\": %s,\n  \"groups\": [\n", descriptionJSON)
	for i, group := range policy.Groups {
		if i > 0 {
			out.WriteString(",\n")
		}
		groupJSON, err := json.Marshal(group)
		if err != nil {
			return err
		}
		fmt.Fprintf(&out, "    %s", groupJSON)
	}
	out.WriteString("\n  ],\n  \"rules\": [\n")
	for i, rule := range rules {
		if i > 0 {
			out.WriteString(",\n")
		}
		ruleJSON, err := json.Marshal(rule)
		if err != nil {
			return err
		}
		fmt.Fprintf(&out, "    %s", ruleJSON)
	}
	out.WriteString("\n  ]\n}\n")
	if err := os.WriteFile(filepath.Join(dir, "ownership.json"), []byte(out.String()), 0644); err != nil {
		return err
	}
	skill, err := os.ReadFile(filepath.Join(dir, "SKILL.md"))
	if err != nil {
		return err
	}
	rendered, err := ownershipTable(string(skill), policy.Groups)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "SKILL.md"), []byte(rendered), 0644)
}
func (r *runner) ownershipFacts(policy ownershipPolicy) (ownershipFacts, error) {
	f := ownershipFacts{importers: map[string][]string{}, generated: map[string]bool{}}
	out, err := r.output("", nil, "git", "ls-files", "-z", "--cached", "--others", "--exclude-standard")
	if err != nil {
		return f, err
	}
	f.paths = strings.Split(strings.TrimSuffix(string(out), "\x00"), "\x00")
	f.paths = slices.DeleteFunc(f.paths, func(p string) bool { _, err := os.Stat(filepath.Join(r.root, p)); return p == "" || err != nil })
	slices.Sort(f.paths)
	f.paths = slices.Compact(f.paths)
	makefile, err := os.ReadFile(filepath.Join(r.root, "Makefile"))
	if err != nil {
		return f, err
	}
	f.binaries, err = parseBinaries(string(makefile), policy.BinaryGroups)
	if err != nil {
		return f, err
	}
	for _, binary := range f.binaries {
		out, err := r.output("", nil, "go", "list", "-deps", "./"+binary.dir)
		if err != nil {
			return f, err
		}
		for pkg := range strings.FieldsSeq(string(out)) {
			if local, ok := strings.CutPrefix(pkg, "github.com/openshift/hypershift/"); ok {
				top, _, _ := strings.Cut(local, "/")
				f.importers[top] = append(f.importers[top], binary.group)
			}
		}
	}
	for top, groups := range f.importers {
		slices.Sort(groups)
		f.importers[top] = slices.Compact(groups)
	}
	for _, pattern := range []string{`output:crd:artifacts:config=(\S+)`, `(?m)^\tcp \S+ (\S+?)/?$`, `(?m)^\tmv \S+ (\S+?)/?$`} {
		for _, match := range regexp.MustCompile(pattern).FindAllStringSubmatch(string(makefile), -1) {
			d := strings.TrimSuffix(strings.TrimPrefix(match[1], "./"), "/")
			if !strings.ContainsAny(d, "$*") && !strings.HasPrefix(d, "/") && !strings.HasPrefix(d, ".") {
				if stat, err := os.Stat(filepath.Join(r.root, d)); err == nil && stat.IsDir() {
					f.outputDirs = append(f.outputDirs, d)
				}
			}
		}
	}
	f.outputDirs = append(f.outputDirs, hypershiftCRDDir, karpenterAssetsDir)
	slices.Sort(f.outputDirs)
	f.outputDirs = slices.Compact(f.outputDirs)
	generatedGO := regexp.MustCompile(`(?m)^// Code generated .* DO NOT EDIT\.$`)
	for _, p := range f.paths {
		if strings.Contains("/"+p, "/vendor/") {
			continue
		}
		if !strings.HasSuffix(p, ".go") && !strings.HasSuffix(p, ".yaml") && !strings.HasSuffix(p, ".yml") {
			continue
		}
		file, err := os.Open(filepath.Join(r.root, p))
		if err != nil {
			continue
		}
		head, _ := io.ReadAll(io.LimitReader(file, 4096))
		file.Close()
		if strings.HasSuffix(p, ".go") {
			if len(head) > 2048 {
				head = head[:2048]
			}
			f.generated[p] = generatedGO.Match(head)
		} else {
			f.generated[p] = bytes.Contains(head, []byte("controller-gen.kubebuilder.io/version"))
		}
	}
	return f, nil
}
func parseBinaries(makefile string, groups map[string]string) ([]ownershipBinary, error) {
	build := regexp.MustCompile(`(?m)^build:(.*)$`).FindStringSubmatch(makefile)
	if build == nil {
		return nil, errors.New("Makefile has no build target")
	}
	var binaries []ownershipBinary
	for _, target := range strings.Fields(build[1]) {
		recipe := regexp.MustCompile(`(?m)^` + regexp.QuoteMeta(target) + `:[^\n]*\n((?:\t[^\n]*\n)+)`).FindStringSubmatch(makefile)
		if recipe == nil {
			return nil, fmt.Errorf("cannot find recipe for make %s", target)
		}
		output := regexp.MustCompile(`(?m)-o \S+ (\.\S*)\s*$`).FindStringSubmatch(recipe[1])
		if output == nil {
			return nil, fmt.Errorf("cannot find package built by make %s", target)
		}
		group, ok := groups[target]
		if !ok {
			return nil, fmt.Errorf("add make %s to repositoryOwnership.BinaryGroups in hack/tools/verify/ownership.go", target)
		}
		binaries = append(binaries, ownershipBinary{target, group, strings.Trim(strings.TrimPrefix(output[1], "."), "/")})
	}
	return binaries, nil
}
func topGroup(top string, isDir bool, p ownershipPolicy, f ownershipFacts) (string, string) {
	if !isDir {
		if strings.HasSuffix(top, ".md") {
			return "Docs", "root documentation"
		}
		if strings.HasSuffix(top, ".go") {
			for _, b := range f.binaries {
				if b.dir == "" {
					return b.group, "source of the binary built from the repository root"
				}
			}
		}
		return "Tooling", "root file"
	}
	if slices.Contains(p.DocDirs, top) {
		return "Docs", "documentation"
	}
	if group, ok := p.ModuleGroups[top]; ok {
		return group, "module " + top + "/"
	}
	for _, b := range f.binaries {
		if b.dir == top {
			return b.group, "package of make " + b.name
		}
		if b.dir == "" && slices.Contains(p.RootSources, top) {
			return b.group, "commands of make " + b.name
		}
	}
	groups := f.importers[top]
	if len(groups) == 1 {
		return groups[0], "imported only by " + groups[0] + " binaries"
	}
	if len(groups) > 0 {
		return "HO", "shared by " + strings.Join(groups, ", ") + " binaries"
	}
	return "Tooling", "not part of any binary"
}
func ownershipRules(p ownershipPolicy, f ownershipFacts) []ownershipRule {
	var rules []ownershipRule
	add := func(pattern, group, why string) { rules = append(rules, ownershipRule{pattern, group, why}) }
	first := func(path string) bool {
		for _, rule := range rules {
			if matchPath(rule.Pattern, path) {
				return true
			}
		}
		return false
	}
	handwritten := func(path string) {
		group, why := topGroup(strings.Split(path, "/")[0], true, p, f)
		add(path, group, "hand-written file in generated output; "+why)
	}
	var vendored, modules, suites []string
	tops := map[string]bool{}
	for _, path := range f.paths {
		if strings.HasSuffix(path, "vendor/modules.txt") && strings.Count(path, "vendor/") == 1 {
			vendored = append(vendored, strings.TrimSuffix(path, "vendor/modules.txt"))
		}
		if strings.HasSuffix(path, "go.mod") && !strings.Contains(path, "vendor/") {
			modules = append(modules, strings.TrimSuffix(strings.TrimSuffix(path, "go.mod"), "/"))
		}
		if strings.HasSuffix(path, ".testsuite.yaml") && strings.Contains(path, "/tests/") {
			i := strings.LastIndex(path, "/tests/")
			suites = append(suites, path[:i]+"/tests")
		}
		top, _, isDir := strings.Cut(path, "/")
		tops[top] = isDir
	}
	slices.Sort(vendored)
	slices.Sort(modules)
	slices.Sort(suites)
	suites = slices.Compact(suites)
	for _, v := range vendored {
		module := strings.TrimSuffix(v, "/")
		if module == "" {
			module = "root"
		}
		add(v+"vendor/**", "Vendor", "vendor tree of module "+module)
	}
	for _, path := range f.paths {
		if strings.HasSuffix(path, ".go") && !f.generated[path] && !first(path) {
			for _, pattern := range p.GeneratedPatterns {
				if matchPath(pattern, path) {
					handwritten(path)
					break
				}
			}
		}
	}
	for _, c := range p.Conventions {
		add(c[0], c[1], c[2])
	}
	for _, suite := range suites {
		add(suite+"/**", "E2E", "envtest suites")
	}
	for _, pattern := range p.GeneratedPatterns {
		add(pattern, "Vendor", "zz_generated output")
	}
	var outDirs []string
	for _, d := range f.outputDirs {
		if first(d + "/x") {
			continue
		}
		nested := false
		for _, other := range f.outputDirs {
			if strings.HasPrefix(d, other+"/") {
				nested = true
			}
		}
		if !nested {
			outDirs = append(outDirs, d)
		}
	}
	for _, d := range outDirs {
		for _, path := range f.paths {
			if strings.HasPrefix(path, d+"/") && strings.HasSuffix(path, ".go") && !f.generated[path] && !first(path) {
				handwritten(path)
			}
		}
	}
	for _, d := range outDirs {
		add(d+"/**", "Vendor", "generated by a Makefile recipe")
	}
	marked := map[string]bool{}
	for path, generated := range f.generated {
		if generated && !first(path) {
			marked[path] = true
		}
	}
	for _, pattern := range collapsePaths(marked, f.paths) {
		add(pattern, "Vendor", "marked as generated")
	}
	for _, m := range modules {
		if group, ok := p.ModuleGroups[m]; ok {
			for _, name := range []string{"go.mod", "go.sum"} {
				module := m
				if module == "" {
					module = "root"
				}
				add(strings.TrimPrefix(m+"/"+name, "/"), group, "definition of module "+module)
			}
		}
	}
	for _, path := range f.paths {
		base := filepath.Base(path)
		if (base == "go.work" || base == "go.work.sum") && !first(path) {
			add(path, "Dependencies", "Go workspace definition")
		}
	}
	keys := make([]string, 0, len(tops))
	for top := range tops {
		keys = append(keys, top)
	}
	slices.Sort(keys)
	for _, top := range keys {
		pattern := top
		if tops[top] {
			pattern += "/**"
		}
		exists := false
		for _, rule := range rules {
			if rule.Pattern == pattern {
				exists = true
			}
		}
		if !exists {
			group, why := topGroup(top, tops[top], p, f)
			add(pattern, group, why)
		}
	}
	return rules
}
func collapsePaths(paths map[string]bool, universe []string) []string {
	children := map[string][]string{}
	for _, p := range universe {
		parts := strings.Split(p, "/")
		for i := 1; i < len(parts); i++ {
			d := strings.Join(parts[:i], "/")
			children[d] = append(children[d], p)
		}
	}
	var full []string
	for d, members := range children {
		all := true
		for _, p := range members {
			if !paths[p] {
				all = false
				break
			}
		}
		if all {
			full = append(full, d)
		}
	}
	slices.Sort(full)
	var patterns []string
	covered := map[string]bool{}
	for _, d := range full {
		nested := false
		for _, o := range full {
			if strings.HasPrefix(d, o+"/") {
				nested = true
				break
			}
		}
		if !nested {
			patterns = append(patterns, d+"/**")
			for _, p := range children[d] {
				covered[p] = true
			}
		}
	}
	var files []string
	for p := range paths {
		if !covered[p] {
			files = append(files, p)
		}
	}
	slices.Sort(files)
	return append(patterns, files...)
}
func matchPath(pattern, value string) bool {
	parts, values := strings.Split(pattern, "/"), strings.Split(value, "/")
	var match func([]string, []string) bool
	match = func(p, v []string) bool {
		if len(p) == 0 {
			return len(v) == 0
		}
		if p[0] == "**" {
			for i := 0; i <= len(v); i++ {
				if match(p[1:], v[i:]) {
					return true
				}
			}
			return false
		}
		if len(v) == 0 {
			return false
		}
		ok, _ := path.Match(p[0], v[0])
		return ok && match(p[1:], v[1:])
	}
	return match(parts, values)
}
func ownershipTable(text string, groups []ownershipGroup) (string, error) {
	const begin = "<!-- BEGIN GENERATED: make ownership-rules -->"
	const end = "<!-- END GENERATED -->"
	start := strings.Index(text, "<!-- BEGIN GENERATED:")
	if start < 0 {
		return "", errors.New("ownership table start marker missing")
	}
	stop := strings.Index(text[start:], end)
	if stop < 0 {
		return "", errors.New("ownership table end marker missing")
	}
	stop += start + len(end)
	lines := []string{begin, "| Order | Group | Commit prefix | Allowed `<type>` | Owns |", "|-------|-------|---------------|------------------|------|"}
	for i, g := range groups {
		types := "fixed"
		if strings.Contains(g.Prefix, "<type>") {
			quoted := make([]string, len(g.Types))
			for j, t := range g.Types {
				quoted[j] = "`" + t + "`"
			}
			types = strings.Join(quoted, ", ")
		}
		lines = append(lines, fmt.Sprintf("| %d | %s | `%s` | %s | %s |", i+1, g.Name, g.Prefix, types, g.Owns))
	}
	lines = append(lines, end)
	return text[:start] + strings.Join(lines, "\n") + text[stop:], nil
}
