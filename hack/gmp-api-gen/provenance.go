package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
)

func writeProvenance(upstream, sourceInfo, output string) error {
	data, err := os.ReadFile(sourceInfo)
	if err != nil {
		return err
	}
	var info struct {
		Path, Version, Sum, GoModSum string
		Origin                       struct{ Hash string }
	}
	if err := json.Unmarshal(data, &info); err != nil {
		return fmt.Errorf("decode upstream module information: %w", err)
	}
	if info.Path != "github.com/GoogleCloudPlatform/prometheus-engine" || info.Version == "" || info.Sum == "" || info.GoModSum == "" {
		return fmt.Errorf("incomplete or unexpected upstream module information")
	}
	if decoded, err := hex.DecodeString(info.Origin.Hash); err != nil || len(decoded) != 20 {
		return fmt.Errorf("upstream module information must include a full Git revision")
	}
	files, err := apiSourceFiles(upstream)
	if err != nil {
		return err
	}
	files = append(files,
		"charts/operator/crds/monitoring.googleapis.com_podmonitorings.yaml",
		"charts/operator/crds/monitoring.googleapis.com_rules.yaml")
	sort.Strings(files)
	var manifest bytes.Buffer
	fmt.Fprintf(&manifest, "# Code generated by hack/update-gmp-api.sh; DO NOT EDIT.\n# Module: %s\n# Version: %s\n# Revision: %s\n# Module sum: %s\n# go.mod sum: %s\n", info.Path, info.Version, info.Origin.Hash, info.Sum, info.GoModSum)
	for _, name := range files {
		contents, err := os.ReadFile(filepath.Join(upstream, name))
		if err != nil {
			return err
		}
		fmt.Fprintf(&manifest, "%x  %s\n", sha256.Sum256(contents), filepath.ToSlash(name))
	}
	return os.WriteFile(filepath.Join(output, "upstream.sha256"), manifest.Bytes(), 0644)
}
