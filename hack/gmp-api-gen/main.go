// gmp-api-gen extracts the data-type closure of the supported GMP resources.
// Runtime methods, interfaces and unrelated resources are deliberately excluded.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	upstream := flag.String("upstream", "", "pinned prometheus-engine source directory")
	output := flag.String("output", "support/gmpmonitoring", "output directory")
	sourceInfo := flag.String("source-info", "", "go mod download JSON for generated provenance")
	flag.Parse()
	if err := generate(*upstream, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if *sourceInfo != "" {
		if err := writeProvenance(*upstream, *sourceInfo, *output); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func generate(upstream, output string) error {
	files, err := apiSourceFiles(upstream)
	if err != nil {
		return err
	}
	fset := token.NewFileSet()
	types := map[string]*ast.GenDecl{}
	typeFiles := map[string]string{}
	sources := map[*ast.GenDecl][]byte{}
	imports := map[*ast.GenDecl]map[string]string{}
	packageOffsets := map[*ast.GenDecl]int{}
	var condition *ast.GenDecl
	for _, name := range files {
		path := filepath.Join(upstream, name)
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		file, err := parser.ParseFile(fset, path, source, parser.ParseComments)
		if err != nil {
			return err
		}
		if file.Name.Name != "v1" {
			return fmt.Errorf("unexpected upstream package %q in %s", file.Name.Name, name)
		}
		fileImports := map[string]string{}
		for _, imp := range file.Imports {
			path, err := strconv.Unquote(imp.Path.Value)
			if err != nil {
				return err
			}
			alias := filepath.Base(path)
			if imp.Name != nil {
				alias = imp.Name.Name
			}
			fileImports[alias] = path
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || (gen.Tok != token.TYPE && gen.Tok != token.CONST) {
				continue
			}
			sources[gen] = source
			imports[gen] = fileImports
			packageOffsets[gen] = fset.Position(file.Package).Offset
			for _, spec := range gen.Specs {
				if typ, ok := spec.(*ast.TypeSpec); ok {
					if existing, ok := typeFiles[typ.Name.Name]; ok {
						return fmt.Errorf("type %q declared in both %s and %s", typ.Name.Name, existing, name)
					}
					types[typ.Name.Name] = gen
					typeFiles[typ.Name.Name] = name
				}
				if val, ok := spec.(*ast.ValueSpec); ok && val.Names[0].Name == "ConfigurationCreateSuccess" {
					condition = gen
				}
			}
		}
	}
	names, err := selectTypes(types)
	if err != nil {
		return err
	}
	usedImports := map[string]string{}
	var body bytes.Buffer
	writeDecl := func(decl *ast.GenDecl) error {
		if err := collectImports(decl, imports[decl], usedImports); err != nil {
			return err
		}
		start := decl.Pos()
		if decl.Doc != nil {
			start = decl.Doc.Pos()
		}
		source := sources[decl][fset.Position(start).Offset:fset.Position(decl.End()).Offset]
		if err := rejectDirectives(source, fset.Position(start).String()); err != nil {
			return err
		}
		body.Write(source)
		body.WriteString("\n\n")
		return nil
	}
	if condition == nil {
		return fmt.Errorf("missing upstream monitoring condition constant")
	}
	if err := writeDecl(condition); err != nil {
		return err
	}
	for _, name := range names {
		if err := writeDecl(types[name]); err != nil {
			return err
		}
	}
	var result bytes.Buffer
	// Preserve the upstream license header and make provenance explicit.
	licenseHeader := sources[types["PodMonitoring"]][:packageOffsets[types["PodMonitoring"]]]
	if err := rejectDirectives(licenseHeader, "license header of "+fset.Position(types["PodMonitoring"].Pos()).Filename); err != nil {
		return err
	}
	result.Write(licenseHeader)
	result.WriteString("// Code generated by hack/update-gmp-api.sh; DO NOT EDIT.\n\npackage gmpmonitoring\n\nimport (\n")
	aliases := make([]string, 0, len(usedImports))
	for alias := range usedImports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		path := usedImports[alias]
		fmt.Fprintf(&result, "%s %q\n", alias, path)
	}
	result.WriteString(")\n\n")
	result.Write(body.Bytes())
	formatted, err := format.Source(result.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(output, "types.go"), formatted, 0644)
}

// rejectDirectives fails when copied upstream source contains Go tool or compiler directives.
// The snapshot is API data only, so directives such as go:generate or go:build must never be copied.
func rejectDirectives(source []byte, location string) error {
	for _, line := range strings.Split(string(source), "\n") {
		line = strings.TrimSpace(line)
		for _, prefix := range []string{"//go:", "// +build", "//line ", "/*line ", "//export "} {
			if strings.HasPrefix(line, prefix) {
				return fmt.Errorf("upstream %s contains Go directive %q; review the upstream change", location, line)
			}
		}
	}
	return nil
}

func collectImports(decl *ast.GenDecl, imports, usedImports map[string]string) error {
	var importError error
	ast.Inspect(decl, func(node ast.Node) bool {
		if selector, ok := node.(*ast.SelectorExpr); ok {
			if alias, ok := selector.X.(*ast.Ident); ok {
				path := imports[alias.Name]
				switch path {
				case "github.com/prometheus/common/model", "k8s.io/api/core/v1", "k8s.io/apimachinery/pkg/apis/meta/v1", "k8s.io/apimachinery/pkg/util/intstr":
				default:
					importError = fmt.Errorf("unsupported API import %q for %s; review the upstream data dependency", path, alias.Name)
					return false
				}
				if previous := usedImports[alias.Name]; previous != "" && previous != path {
					importError = fmt.Errorf("conflicting upstream import alias %s: %s and %s", alias.Name, previous, path)
					return false
				}
				usedImports[alias.Name] = path
			}
		}
		return true
	})
	return importError
}

func selectTypes(types map[string]*ast.GenDecl) ([]string, error) {
	selected := map[string]bool{}
	var visit func(string) error
	visit = func(name string) error {
		if selected[name] {
			return nil
		}
		decl, ok := types[name]
		if !ok {
			return fmt.Errorf("missing upstream type %s", name)
		}
		if len(decl.Specs) != 1 {
			return fmt.Errorf("unsupported grouped upstream type declaration for %s", name)
		}
		spec := decl.Specs[0].(*ast.TypeSpec)
		if _, ok := spec.Type.(*ast.InterfaceType); ok {
			return fmt.Errorf("API data unexpectedly depends on interface %s", name)
		}
		selected[name] = true
		var err error
		var inspect func(ast.Node) bool
		inspect = func(node ast.Node) bool {
			switch node := node.(type) {
			case *ast.Field:
				ast.Inspect(node.Type, inspect)
				return false // Field names are declarations, not type references.
			case *ast.SelectorExpr:
				return false // External types are imports, not part of the local closure.
			case *ast.InterfaceType:
				err = fmt.Errorf("API data unexpectedly depends on interface in %s", name)
				return false
			}
			if id, ok := node.(*ast.Ident); ok && types[id.Name] != nil && err == nil {
				err = visit(id.Name)
			}
			return err == nil
		}
		ast.Inspect(spec.Type, inspect)
		return err
	}
	for _, name := range []string{"PodMonitoring", "PodMonitoringList", "Rules", "RulesList"} {
		if err := visit(name); err != nil {
			return nil, err
		}
	}
	names := make([]string, 0, len(selected))
	for name := range selected {
		names = append(names, name)
	}
	sort.Strings(names)
	return names, nil
}

func apiSourceFiles(upstream string) ([]string, error) {
	const directory = "pkg/operator/apis/monitoring/v1"
	entries, err := os.ReadDir(filepath.Join(upstream, directory))
	if err != nil {
		return nil, err
	}
	var files []string
	for _, entry := range entries {
		name := entry.Name()
		if !entry.IsDir() && strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") && !strings.HasPrefix(name, "zz_generated.") {
			files = append(files, filepath.Join(directory, name))
		}
	}
	return files, nil
}
